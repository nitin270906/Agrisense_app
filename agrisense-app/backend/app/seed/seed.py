"""Seed demo farms, fields and 150 days of sensor history.

The fields are authored, not randomised. A demo needs to *show* the product's
range within about ninety seconds, so the seed deliberately spans every risk
band and every failure mode the tool is built to catch: a healthy well-drained
plot, a salt-sensitive crop irrigated with brackish water over a shallow water
table, a canal tail-ender that misses turns, and a coastal plot fighting
saltwater intrusion.

History is generated by the physics simulator under synthetic weather rather
than fetched from the network, so seeding works with no connection and produces
identical data every run.
"""
